import React from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { QueryClient,QueryClientProvider } from '@tanstack/react-query';
import '@fontsource/inter/400.css';
import '@fontsource/inter/500.css';
import '@fontsource/inter/600.css';
import '@fontsource/inter/700.css';
import './styles.css';
import { App } from './App';
const client=new QueryClient({defaultOptions:{queries:{retry:(count,error)=>count<1&&(!('status'in error)||Number(error.status)>=500),staleTime:15000,refetchOnWindowFocus:true}}});
createRoot(document.getElementById('root')!).render(<React.StrictMode><QueryClientProvider client={client}><BrowserRouter basename="/app"><App/></BrowserRouter></QueryClientProvider></React.StrictMode>);
