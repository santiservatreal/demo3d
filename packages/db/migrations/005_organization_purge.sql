-- Only organizations explicitly deleted for seven days can be purged. IDs remain tombstoned.
CREATE FUNCTION vault.purge_deleted_organizations() RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,birdview_private,vault AS $$
DECLARE target record;n integer:=0; BEGIN
 SET CONSTRAINTS ALL DEFERRED;
 FOR target IN SELECT o.id FROM public.organizations o JOIN birdview_private.deletion_tombstones d ON d.organization_id=o.id WHERE o.deleted_at<now()-interval '7 days' AND d.purged_at IS NULL LIMIT 20 LOOP
 INSERT INTO birdview_private.object_gc(organization_id,storage_key,backend) SELECT organization_id,data->>'storageKey',data->>'storageBackend' FROM public.artifacts WHERE organization_id=target.id AND data->>'storageKey' IS NOT NULL AND data->>'storageBackend' IN('local','s3') ON CONFLICT DO NOTHING;
 DELETE FROM public.zod WHERE organization_id=target.id;
 DELETE FROM public.accounts WHERE organization_id=target.id;
 DELETE FROM public.contacts WHERE organization_id=target.id;
 DELETE FROM public.employees WHERE organization_id=target.id;
 DELETE FROM public.teams WHERE organization_id=target.id;
 DELETE FROM public.opportunities WHERE organization_id=target.id;
 DELETE FROM public.pipelines WHERE organization_id=target.id;
 DELETE FROM public.stages WHERE organization_id=target.id;
 DELETE FROM public.invoices WHERE organization_id=target.id;
 DELETE FROM public.payments WHERE organization_id=target.id;
 DELETE FROM public.tickets WHERE organization_id=target.id;
 DELETE FROM public.products WHERE organization_id=target.id;
 DELETE FROM public.inventory_movements WHERE organization_id=target.id;
 DELETE FROM public.orders WHERE organization_id=target.id;
 DELETE FROM public.projects WHERE organization_id=target.id;
 DELETE FROM public.connections WHERE organization_id=target.id;
 DELETE FROM public.sync_runs WHERE organization_id=target.id;
 DELETE FROM public.cursors WHERE organization_id=target.id;
 DELETE FROM public.source_records WHERE organization_id=target.id;
 DELETE FROM public.source_entity_links WHERE organization_id=target.id;
 DELETE FROM public.schema_mappings WHERE organization_id=target.id;
 DELETE FROM public.metric_definitions WHERE organization_id=target.id;
 DELETE FROM public.metric_snapshots WHERE organization_id=target.id;
 DELETE FROM public.entity_events WHERE organization_id=target.id;
 DELETE FROM public.evidence_records WHERE organization_id=target.id;
 DELETE FROM public.data_quality_issues WHERE organization_id=target.id;
 DELETE FROM public.conversations WHERE organization_id=target.id;
 DELETE FROM public.messages WHERE organization_id=target.id;
 DELETE FROM public.answer_blocks WHERE organization_id=target.id;
 DELETE FROM public.query_executions WHERE organization_id=target.id;
 DELETE FROM public.evidence_links WHERE organization_id=target.id;
 DELETE FROM public.knowledge_items WHERE organization_id=target.id;
 DELETE FROM public.knowledge_versions WHERE organization_id=target.id;
 DELETE FROM public.knowledge_sources WHERE organization_id=target.id;
 DELETE FROM public.knowledge_conflicts WHERE organization_id=target.id;
 DELETE FROM public.action_proposals WHERE organization_id=target.id;
 DELETE FROM public.approvals WHERE organization_id=target.id;
 DELETE FROM public.execution_attempts WHERE organization_id=target.id;
 DELETE FROM public.tasks WHERE organization_id=target.id;
 DELETE FROM public.task_steps WHERE organization_id=target.id;
 DELETE FROM public.routines WHERE organization_id=target.id;
 DELETE FROM public.routine_runs WHERE organization_id=target.id;
 DELETE FROM public.report_templates WHERE organization_id=target.id;
 DELETE FROM public.report_runs WHERE organization_id=target.id;
 DELETE FROM public.artifacts WHERE organization_id=target.id;
 DELETE FROM public.presentation_documents WHERE organization_id=target.id;
 DELETE FROM public.media_jobs WHERE organization_id=target.id;
 DELETE FROM public.ai_provider_configs WHERE organization_id=target.id;
 DELETE FROM public.model_capabilities WHERE organization_id=target.id;
 DELETE FROM public.privacy_policies WHERE organization_id=target.id;
 DELETE FROM public.budget_limits WHERE organization_id=target.id;
 DELETE FROM public.usage_ledger WHERE organization_id=target.id;
 DELETE FROM public.api_keys WHERE organization_id=target.id;
 DELETE FROM public.published_queries WHERE organization_id=target.id;
 DELETE FROM public.webhook_subscriptions WHERE organization_id=target.id;
 DELETE FROM public.privacy_decisions WHERE organization_id=target.id;
 DELETE FROM public.encrypted_credentials WHERE organization_id=target.id;
 DELETE FROM public.departments WHERE organization_id=target.id;
 DELETE FROM public.roles WHERE organization_id=target.id;
 DELETE FROM public.permissions WHERE organization_id=target.id;
 DELETE FROM public.bindings WHERE organization_id=target.id;
 DELETE FROM vault.pseudonym_mappings WHERE organization_id=target.id;
 DELETE FROM public.audit_events WHERE organization_id=target.id;
 DELETE FROM birdview_private.api_principals WHERE organization_id=target.id;
 DELETE FROM birdview_private.invitations WHERE organization_id=target.id;
 DELETE FROM public.memberships WHERE organization_id=target.id;
 UPDATE public.organizations SET name='Deleted organization',modules='{}' WHERE id=target.id;
 UPDATE birdview_private.deletion_tombstones SET purged_at=now() WHERE organization_id=target.id;n:=n+1;
 END LOOP;RETURN n;END $$;
REVOKE ALL ON FUNCTION vault.purge_deleted_organizations() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION vault.purge_deleted_organizations() TO birdview_vault;
